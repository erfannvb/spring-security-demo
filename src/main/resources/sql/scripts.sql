CREATE TABLE account_transactions
(
    transaction_id      VARCHAR(200) NOT NULL,
    account_number      INT          NOT NULL,
    customer_id         BIGINT       NOT NULL,
    transaction_dt      DATE         NOT NULL,
    transaction_summary VARCHAR(200) NOT NULL,
    transaction_type    VARCHAR(100) NOT NULL,
    transaction_amt     INT          NOT NULL,
    closing_balance     INT          NOT NULL,
    create_dt           DATE DEFAULT NULL,
    PRIMARY KEY (transaction_id),
    CONSTRAINT transactions_account_fk
        FOREIGN KEY (account_number)
            REFERENCES accounts (account_number)
            ON DELETE CASCADE,
    CONSTRAINT transactions_user_fk
        FOREIGN KEY (customer_id)
            REFERENCES users (id)
            ON DELETE CASCADE
);

CREATE INDEX idx_transactions_customer_id
    ON account_transactions (customer_id);

CREATE INDEX idx_transactions_account_number
    ON account_transactions (account_number);

